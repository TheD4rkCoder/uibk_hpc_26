#!/usr/bin/env python3
"""Parse OSU MPI benchmark logs from a results directory.

This script expects files named like:
  latency_output_same_socket.log
  bandwidth_output_diff_socket.log

It aggregates repeated OSU blocks in each file, computes the mean and variance per
message size, emits a comparison plot for latency and bandwidth, and writes a
Markdown summary table for each metric.

This script was generated by ChatGPT.
"""

import argparse
import math
import re
import statistics
from collections import defaultdict
from pathlib import Path
from typing import Dict, List, Optional, Tuple

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt


SIZE_LINE_RE = re.compile(r"^\s*(\d+)\s+([+-]?(?:\d+(?:\.\d*)?|\.\d+)(?:[eE][+-]?\d+)?)\s*$")
OSU_HEADER_RE = re.compile(r"^#\s*OSU\s+MPI.*$")


def parse_osu_log(path: Path) -> List[Dict[int, float]]:
    """Return one dict per repeated OSU output block in a log file."""
    runs: List[Dict[int, float]] = []
    current: Optional[Dict[int, float]] = None

    for raw_line in path.read_text(encoding="utf-8", errors="replace").splitlines():
        line = raw_line.strip()

        if not line:
            continue

        if OSU_HEADER_RE.match(line):
            if current is not None:
                runs.append(current)
            current = {}
            continue

        if line.startswith("# Size"):
            continue

        if line.startswith("#"):
            continue

        if current is None:
            continue

        match = SIZE_LINE_RE.match(raw_line)
        if match is None:
            continue

        size = int(match.group(1))
        value = float(match.group(2))
        current[size] = value

    if current is not None:
        runs.append(current)

    if not runs:
        raise ValueError(f"No benchmark data found in {path}")

    return runs


def aggregate_runs(runs: List[Dict[int, float]]) -> Tuple[List[int], Dict[int, float], Dict[int, float]]:
    size_values = defaultdict(list)
    for run in runs:
        for size, value in run.items():
            size_values[size].append(value)

    sorted_sizes = sorted(size_values)
    means: Dict[int, float] = {}
    variances: Dict[int, float] = {}

    for size in sorted_sizes:
        values = size_values[size]
        means[size] = statistics.mean(values)
        if len(values) > 1:
            variances[size] = statistics.pvariance(values)
        else:
            variances[size] = 0.0

    return sorted_sizes, means, variances


def style_from_filename(path: Path, metric: str) -> str:
    prefix = f"{metric}_output_"
    stem = path.stem
    if not stem.startswith(prefix):
        raise ValueError(f"Unexpected file name: {path.name}")
    return stem[len(prefix):]


def plot_metric(results_dir: Path, metric: str, aggregated: Dict[str, Tuple[List[int], Dict[int, float], Dict[int, float]]]) -> Path:
    styles = sorted(aggregated)
    fig, ax = plt.subplots(figsize=(10, 6))

    for style in styles:
        sizes, means, variances = aggregated[style]
        std = {size: math.sqrt(variances[size]) for size in sizes}
        xs = sizes
        ys = [means[s] for s in sizes]
        yerr = [std[s] for s in sizes]

        ax.plot(xs, ys, marker="o", linewidth=2, label=style.replace("_", " ").title())
        ax.errorbar(xs, ys, yerr=yerr, fmt="none", alpha=0.25, capsize=3)

    ax.set_title(f"{metric.replace('_', ' ').title()} comparison across execution styles")
    ax.set_xlabel("Message size (bytes)")
    if metric == "latency":
        ax.set_ylabel("Latency (us)")
    elif metric == "bandwidth":
        ax.set_ylabel("Bandwidth (MB/s)")
    ax.set_xscale("log", basex=2)
    ax.set_yscale("log", basey=2)
    ax.grid(True, which="both", linestyle="--", linewidth=0.7, alpha=0.5)
    ax.legend()
    fig.tight_layout()

    out_path = results_dir / f"{metric}_comparison.png"
    fig.savefig(out_path, dpi=200)
    plt.close(fig)
    return out_path


def markdown_table(metric: str, aggregated: Dict[str, Tuple[List[int], Dict[int, float], Dict[int, float]]]) -> str:
    styles = sorted(aggregated)
    all_sizes = sorted({size for _, means, _ in aggregated.values() for size in means})

    unit = "us" if metric == "latency" else "MB/s"
    header = ["Message size"]
    for style in styles:
        header.extend([
            f"{style} mean ({unit})",
            f"{style} stdev ({unit})",
        ])

    lines = [
        "| " + " | ".join(header) + " |",
        "| " + " | ".join(["---"] * len(header)) + " |",
    ]

    for size in all_sizes:
        row = [str(size)]
        for style in styles:
            _, means, variances = aggregated[style]
            if size in means:
                row.append(f"{means[size]:.3f}")
                row.append(f"{math.sqrt(variances[size]):.3f}")
            else:
                row.append("-")
                row.append("-")
        lines.append("| " + " | ".join(row) + " |")

    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description="Parse OSU MPI benchmark logs and generate plots/tables.")
    parser.add_argument("--results-dir", type=Path, default=Path(__file__).resolve().parent / "results", help="Directory containing the benchmark log files.")
    args = parser.parse_args()

    results_dir = args.results_dir.resolve()
    if not results_dir.exists():
        raise FileNotFoundError(f"Results directory not found: {results_dir}")

    per_metric: Dict[str, Dict[str, Tuple[List[int], Dict[int, float], Dict[int, float]]]] = {
        "latency": {},
        "bandwidth": {},
    }

    for file_path in sorted(results_dir.glob("*.log")):
        if file_path.name.startswith("latency_output_"):
            metric = "latency"
        elif file_path.name.startswith("bandwidth_output_"):
            metric = "bandwidth"
        else:
            continue

        style = style_from_filename(file_path, metric)
        runs = parse_osu_log(file_path)
        sizes, means, variances = aggregate_runs(runs)
        per_metric[metric][style] = (sizes, means, variances)

    for metric in ("latency", "bandwidth"):
        if not per_metric[metric]:
            continue

        plot_path = plot_metric(results_dir, metric, per_metric[metric])
        table_text = markdown_table(metric, per_metric[metric])

        md_path = results_dir / f"{metric}_summary.md"
        md_path.write_text(f"# {metric.replace('_', ' ').title()} summary\n\n{table_text}", encoding="utf-8")

        print(f"Generated {plot_path.name} and {md_path.name} for {metric}.")


if __name__ == "__main__":
    main()
